/* -------------------------------------------------------------------------
 | تشخیص تب پیشنهادی از روی دستهٔ محصول
 |------------------------------------------------------------------------*/

export function resolveSizeGuideTab(
  categorySlug?: string | null,
  variantNames: string[] = [],
): SizeGuideTabId {
  const slug = (categorySlug ?? "").toLowerCase();

  if (slug.startsWith("bra")) {
    return "bra";
  }

  if (slug.startsWith("pant")) {
    return "panties";
  }

  if (slug.startsWith("shapewear") || slug.startsWith("lingerie-sets")) {
    return "clothes";
  }

  if (slug.startsWith("sleepwear")) {
    return "clothes";
  }

  // اگر دسته مشخص نبود، از برچسب تنوع‌ها کمک می‌گیریم؛ سایزهایی مثل
  // «75B» نشانهٔ سوتین و «S/M/L» نشانهٔ لباس هستند.
  const looksLikeBra = variantNames.some((name) =>
    /\d{2,3}\s*[A-F]{1,2}/i.test(name),
  );

  if (looksLikeBra) {
    return "bra";
  }

  return "clothes";
}

