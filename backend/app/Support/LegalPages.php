- در بخش «مرجوعی و بازپرداخت»، دلیل مرجوعی را بنویسید و درخواست را ثبت کنید.
- وضعیت درخواست (در انتظار بررسی / تأییدشده / ردشده / بازپرداخت‌شده) در همان صفحه نمایش داده می‌شود.
- پس از تأیید، نحوهٔ ارسال مرسولهٔ برگشتی (پست یا پیک) به شما اعلام می‌شود.

