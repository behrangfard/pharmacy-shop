    /**
     * جایگزینی متغیرهای {{...}} با مقادیر تنظیمات فروشگاه.
     *
     * @param  array<string, string|int|float|null>  $settings
     */
    public static function render(string $text, array $settings): string
    {
        $replacements = [];

        foreach (self::PLACEHOLDERS as $key) {
            $value = $settings[$key] ?? '';

            if ($value === null) {
                $value = '';
            }

            $replacements['{{'.$key.'}}'] = (string) $value;
        }

        return strtr($text, $replacements);
    }

